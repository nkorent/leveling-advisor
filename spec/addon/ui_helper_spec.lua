-- The fake widget toolkit in spec/helpers/ui.lua (later UI tasks rely on it).
local ui = require("spec.helpers.ui")

describe("spec.helpers.ui", function()
  local ns, env, fake
  before_each(function() ns, env, fake = ui.load({ noData = true }) end)

  it("FILES follows the TOC without Data/", function()
    assert.equal("Core/DB.lua", ui.FILES[1])
    assert.equal("Engine/Tuning.lua", ui.FILES[2])
    local pos = {}
    for i, f in ipairs(ui.FILES) do
      pos[f] = i
      assert.falsy(f:match("^Data/"))
    end
    assert.is_true(pos["Engine/Engine.lua"] < pos["Core/Util.lua"])
    assert.is_true(pos["Core/Slash.lua"] < pos["UI/MapPins.lua"])
    assert.is_true(pos["UI/MapPins.lua"] < pos["UI/Style.lua"])
    assert.is_true(pos["UI/Style.lua"] < pos["UI/Window.lua"])
    assert.equal("UI/QuestLogTab.lua", ui.FILES[#ui.FILES])
  end)

  it("named frames become globals; children belong to their parent", function()
    local f = fake.newFrame("Frame", "LevelingAdvisorTestFrame", env.UIParent)
    assert.equal(f, env.LevelingAdvisorTestFrame)
    assert.equal(f, fake.named("LevelingAdvisorTestFrame"))
    local t = f:CreateTexture(nil, "ARTWORK")
    assert.equal(f, t:GetParent())
    assert.equal("Texture", t:GetObjectType())
  end)

  it("records unknown capitalised methods", function()
    local f = fake.newFrame("Frame")
    assert.is_nil(f:SomethingNew(1, 2))
    assert.same({ "SomethingNew", 1, 2 }, f.calls[1])
    assert.is_nil(f.lowercaseField)
  end)

  it("points: SetPoint replaces the same anchor point", function()
    local f = fake.newFrame("Frame", nil, env.UIParent)
    f:SetPoint("TOPLEFT", 3, 4)
    assert.same({ "TOPLEFT", env.UIParent, "TOPLEFT", 3, 4 }, { f:GetPoint(1) })
    f:SetPoint("TOPLEFT", env.UIParent, "CENTER", 5, 6)
    assert.equal(1, f:GetNumPoints())
    assert.same({ "TOPLEFT", env.UIParent, "CENTER", 5, 6 }, { f:GetPoint(1) })
  end)

  it("Show and Hide run OnShow and OnHide; HookScript chains after the script", function()
    local f = fake.newFrame("Frame")
    local seen = {}
    f:SetScript("OnShow", function() seen[#seen + 1] = "script" end)
    f:HookScript("OnShow", function() seen[#seen + 1] = "hook" end)
    f:Show()
    assert.same({}, seen) -- already shown: no event
    f:Hide()
    f:Show()
    assert.same({ "script", "hook" }, seen)
  end)

  it("visible follows the parents; text prefers a visible widget", function()
    local hidden = fake.newFrame("Frame")
    hidden:Hide()
    local a = hidden:CreateFontString()
    a:SetText("Darkshore")
    local b = fake.newFrame("Frame"):CreateFontString()
    b:SetText("Darkshore")
    assert.is_false(fake.visible(a))
    assert.equal(b, fake.text("Darkshore"))
    b:GetParent():Hide()
    assert.equal(a, fake.text("Darkshore"))
  end)

  it("GetStringHeight counts 14 px lines", function()
    local fs = fake.newFrame("Frame"):CreateFontString()
    fs:SetWidth(60)
    fs:SetText(string.rep("x", 25)) -- 150 px of text in 60 px: 3 lines
    assert.equal(42, fs:GetStringHeight())
  end)

  it("click toggles a check button and skips a disabled button", function()
    local cb = fake.newFrame("CheckButton", nil, nil, "UICheckButtonTemplate")
    assert.is_table(cb.Text)
    local clicks = {}
    cb:SetScript("OnClick", function(self, button) clicks[#clicks + 1] = { self:GetChecked(), button } end)
    fake.click(cb)
    assert.same({ { true, "LeftButton" } }, clicks)
    cb:Disable()
    fake.click(cb, "RightButton")
    assert.equal(1, #clicks)
  end)

  it("type sets the text and runs OnTextChanged as user input", function()
    local box = fake.newFrame("EditBox", nil, nil, "SearchBoxTemplate")
    assert.is_table(box.Instructions)
    local got
    box:SetScript("OnTextChanged", function(self, user) got = { self:GetText(), user } end)
    fake.type(box, "tower")
    assert.same({ "tower", true }, got)
  end)

  it("WowScrollBoxList lays out rows on the box and reuses them by position", function()
    local box = fake.newFrame("Frame", nil, env.UIParent, "WowScrollBoxList")
    local bar = fake.newFrame("EventFrame", nil, env.UIParent, "MinimalScrollBar")
    local view = env.CreateScrollBoxListLinearView()
    view:SetElementInitializer("LevelingAdvisorListRowTemplate", function(frame, e) frame:SetText(e.name) end)
    view:SetElementExtentCalculator(function(i) return 40 + i end)
    env.ScrollUtil.InitScrollBoxListWithScrollBar(box, bar, view)
    box:SetDataProvider(env.CreateDataProvider({ { name = "a" }, { name = "b" }, { name = "c" } }))
    assert.equal(3, #box.rows)
    local first = box.rows[1].frame
    assert.equal(box, first:GetParent())
    assert.equal("LevelingAdvisorListRowTemplate", first.template)
    assert.equal("b", box.rows[2].frame:GetText())
    assert.equal(42, box.rows[2].extent)
    assert.equal("c", box.rows[3].element.name)
    local third = box.rows[3].frame

    local dp = env.CreateDataProvider()
    dp:Insert({ name = "x" })
    box:SetDataProvider(dp, env.ScrollBoxConstants.RetainScrollPosition)
    assert.equal(1, #box.rows)
    assert.equal(first, box.rows[1].frame)
    assert.equal("x", first:GetText())
    assert.is_false(third:IsShown())
    box:Hide()
    assert.is_false(fake.visible(first))
  end)

  it("WowScrollBoxList supports an element factory", function()
    local box = fake.newFrame("Frame", nil, env.UIParent, "WowScrollBoxList")
    local view = env.CreateScrollBoxListLinearView()
    view:SetElementFactory(function(factory, e)
      factory("LevelingAdvisorListRowTemplate", function(frame) frame:SetText(e.kind) end)
    end)
    view:SetElementExtent(30)
    env.ScrollUtil.InitScrollBoxListWithScrollBar(box, nil, view)
    box:SetDataProvider(env.CreateDataProvider({ { kind = "header" }, { kind = "row" } }))
    assert.equal("row", box.rows[2].frame:GetText())
    assert.equal(30, box.rows[1].extent)
  end)

  it("tooltip records the owner and lines", function()
    local owner = fake.newFrame("Button")
    env.GameTooltip:SetOwner(owner, "ANCHOR_RIGHT")
    env.GameTooltip:SetText("Title", 1, 1, 1)
    env.GameTooltip:AddLine("Body", 0.5, 0.5, 0.5, true)
    env.GameTooltip:SetItemByID(7750)
    env.GameTooltip:Show()
    assert.same({ owner = owner, lines = { { "Title", 1, 1, 1 }, { "Body", 0.5, 0.5, 0.5 } }, itemID = 7750, shown = true },
      { owner = fake.tooltip.owner, lines = fake.tooltip.lines, itemID = fake.tooltip.itemID, shown = fake.tooltip.shown })
  end)

  it("setState hands out a fresh copy on every snapshot", function()
    local ns2, _, fake2 = ui.load({ state = "S18" })
    local a = ns2.Adapter.snapshot()
    a.level = 60
    assert.equal(18, ns2.Adapter.snapshot().level)
    assert.equal(18, ns2.Advisor.last.state.level)
    fake2.setState({ level = 5, completed = {}, log = {}, ignored = {}, settings = {} })
    assert.equal(5, ns2.Adapter.snapshot().level)
  end)

  it("spy counts calls, keeps the args and passes through", function()
    local t = { add = function(a, b) return a + b end }
    local spy = ui.spy(t, "add")
    assert.equal(5, t.add(2, 3))
    assert.equal(1, spy.n)
    assert.same({ n = 2, 2, 3 }, spy.calls[1])
    local stub = ui.spy(t, "add", function() return 0 end)
    assert.equal(0, t.add(1, 1))
    assert.equal(1, stub.n)
  end)

  it("combat and flush", function()
    local ran = false
    env.C_Timer.After(0.4, function() ran = env.InCombatLockdown() end)
    fake.combat(true)
    fake.flush()
    assert.is_true(ran)
    assert.same({}, env.errors)
    assert.is_table(ns.Events)
  end)
end)
