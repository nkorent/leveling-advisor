# ---------------------------------------------------------------- loaders

def _run(runner: str, path: Path):
    src = Path(path).read_text(encoding="utf-8-sig")
    lua = lupa.LuaRuntime(register_eval=False, register_builtins=False)
    try:
        return lua.eval(runner)(src, Path(path).name)
    except lupa.LuaError as e:
        raise ValueError(f"cannot run {path}: {e}") from e


def _py(v):
    """Lua scalar -> Python (nil, boolean, number, string); whole floats stay floats (coordinates)."""
    if isinstance(v, bytes):
        return v.decode("utf-8")
    if v is None or isinstance(v, (bool, int, float, str)):
        return v
    raise ValueError(f"unexpected {lupa.lua_type(v) or type(v).__name__} value")


def _whole(v):
    """An id or level: whole numbers become int, anything else is returned unchanged."""
    if isinstance(v, float) and v.is_integer():
        return int(v)
    return v


def _array(t, what: str, optional: bool = False, extra=()) -> list:
    """A Lua list 1..n as a Python list; `extra` names the only non-index keys allowed."""
    if t is None and optional:
        return []
    if lupa.lua_type(t) != "table":
        raise ValueError(f"{what} is not a table")
    keys = list(t.keys())
    named = [k for k in keys if type(k) is not int]
    unknown = [k for k in named if k not in extra]
    if unknown:
        raise ValueError(f"{what} has unknown field(s) {', '.join(map(str, unknown))}")
    index = sorted(k for k in keys if type(k) is int)
    if index != list(range(1, len(index) + 1)):
        raise ValueError(f"{what} is not a list")
    return [t[i] for i in index]


def _member(t, what: str) -> dict:
    v = _array(t, what)
    if len(v) != 5:
        raise ValueError(f"{what} is not {{mapID, name, raid, minLevel, maxLevel}}")
    try:
        v = [_py(x) for x in v]
    except ValueError as e:
        raise ValueError(f"{what}: {e}") from None
    if not isinstance(v[1], str) or not isinstance(v[2], bool):
        raise ValueError(f"{what}: name must be a string and raid a boolean")
    return {"id": _whole(v[0]), "name": v[1], "raid": v[2], "min_level": _whole(v[3]), "max_level": _whole(v[4])}


def load_openmap_places(path: Path) -> dict:
    """OpenMap Places.lua (ns.MapPlaces) -> plain data.

    {"instances": [{continent, x, y, map, members: [{id, name, raid, min_level, max_level}]}],
     "unplaced": [{id, name, raid, min_level, max_level}],
     "transports": [{kind, route, continent, x, y, to_continent, to_x, to_y[, faction]}]}
    An instance is either in world yards (continent, x, y; map None) or a spot on the zone map
    ``map`` (continent None, x and y 0..1). A transport's optional ``faction`` (Alliance or Horde)
    marks one faction's only transport.
    """
    places = _run(_OPENMAP_LUA, path)
    if lupa.lua_type(places) != "table":
        raise ValueError(f"{path} does not set ns.MapPlaces")
    out = {"instances": [], "unplaced": [], "transports": []}
    for i, g in enumerate(_array(places["instances"], f"{path}: instances", optional=True), 1):
        what = f"{path}: instances[{i}]"
        if lupa.lua_type(g) != "table":
            raise ValueError(f"{what} is not a table")
        members = [_member(m, f"{what} member") for m in _array(g[4], f"{what} members")]
        try:
            out["instances"].append({"continent": _whole(_py(g[1])), "x": _py(g[2]), "y": _py(g[3]),
                                     "map": _whole(_py(g["map"])), "members": members})
        except ValueError as e:
            raise ValueError(f"{what}: {e}") from None
    for i, m in enumerate(_array(places["unplaced"], f"{path}: unplaced", optional=True), 1):
        out["unplaced"].append(_member(m, f"{path}: unplaced[{i}]"))
    for i, t in enumerate(_array(places["transports"], f"{path}: transports", optional=True), 1):
        what = f"{path}: transports[{i}]"
        try:
            v = [_py(x) for x in _array(t, what, extra=("faction",))]
            faction = _py(t["faction"])
        except ValueError as e:
            raise ValueError(f"{what}: {e}") from None
        if len(v) != 8:
            raise ValueError(f"{what} does not have 8 fields")
        if faction is not None and faction not in LINK_FACTIONS:
            raise ValueError(f"{what}: faction {faction!r} is not one of {', '.join(LINK_FACTIONS)}")
        row = dict(zip(TRANSPORT_FIELDS, [v[0], v[1], _whole(v[2]), v[3], v[4], _whole(v[5]), v[6], v[7]]))
        if faction is not None:
            row["faction"] = faction
        out["transports"].append(row)
    return out


def load_openmap_levels(path: Path) -> dict[int, tuple[int, int]]:
    """OpenMap Levels.lua (``ns.MapLevels[uiMapID] = {min, max}``, MIT) -> {uiMapID: (min, max)}.

    Run in the same empty-environment sandbox as Places.lua. A malformed row (not two whole
    numbers, or min above max) is skipped: that zone then falls back to quest percentiles.
    """
    levels = _run(_OPENMAP_LEVELS_LUA, path)
    if lupa.lua_type(levels) != "table":
        raise ValueError(f"{path} does not set ns.MapLevels")
    out = {}
    for k in levels.keys():
        row = levels[k]
        k = _whole(k)
        if type(k) is not int or lupa.lua_type(row) != "table":
            continue
        lo, hi = _whole(row[1]), _whole(row[2])
        if type(lo) is int and type(hi) is int and 1 <= lo <= hi:
            out[k] = (lo, hi)
    return out


# ---------------------------------------------------------------- bounds gate and conversion

def check_bounds(census: dict) -> dict:
    """The gate: CONTINENT_BOUNDS are used only if, for each continent, left - right and top - bottom
    reproduce the census continent `yards` within BOUNDS_TOLERANCE. ValueError otherwise (never fitted).
    Returns {continent: {"bounds_yards": [w, h], "census_yards": [w, h], "difference": [dw, dh]}}."""
    out = {}
    for continent, (left, right, top, bottom) in CONTINENT_BOUNDS.items():
        m = census["maps"].get(continent)
        yards = (m or {}).get("yards")
        if not isinstance(yards, list) or len(yards) != 2 or not all(_num(v) for v in yards):
            raise ValueError(f"bounds gate: census map {continent} has no continent yards")
        size = [left - right, top - bottom]
        diff = [round(size[0] - yards[0], 4), round(size[1] - yards[1], 4)]
        if any(abs(d) > BOUNDS_TOLERANCE for d in diff):
            raise ValueError(f"bounds gate failed for continent {continent} ({m.get('name')}): bounds give "
                             f"{size[0]:.2f} x {size[1]:.2f} yd, the census says {yards[0]:.2f} x {yards[1]:.2f}")
        out[continent] = {"bounds_yards": size, "census_yards": list(yards), "difference": diff}
    return out


def world_to_continent(continent: int, world_x: float, world_y: float) -> tuple[float, float]:
    """World yards on a continent (X north, Y west) -> 0..1 on the census continent map."""
    left, right, top, bottom = CONTINENT_BOUNDS[continent]
    return (left - world_y) / (left - right), (top - world_x) / (top - bottom)


# ---------------------------------------------------------------- zone choice

class ZoneHints:
    """openmap_zone_hints.toml: per table ("instances", "transports"), an OpenMap name -> zone
    uiMapIDs in order of preference. Remembers which names were consulted."""

    def __init__(self, tables: dict | None = None):
        self.tables = {t: dict(v) for t, v in (tables or {}).items()}
        self.used: set[tuple[str, str]] = set()
        self.points = 0          # points whose zone a hint chose

    def lookup(self, table: str, names) -> tuple[list[int] | None, list[str]]:
        """(the hinted uiMapIDs, the names that matched); (None, names) when they disagree."""
        rows = self.tables.get(table) or {}
        matched = list(dict.fromkeys(n for n in names if n in rows))
        hinted = {tuple(rows[n]) for n in matched}
        if len(hinted) > 1:
            return None, matched
        return (list(hinted.pop()) if hinted else []), matched

    def decided(self, table: str, matched) -> None:
        """A hint chose a point's zone: its names count as used."""
        self.used.update((table, n) for n in matched)
        self.points += 1

    def unused(self) -> list[dict]:
        return [{"type": "unused-hint", "table": t, "name": n}
                for t in sorted(self.tables) for n in self.tables[t] if (t, n) not in self.used]


def load_zone_hints(path: Path, census: dict) -> ZoneHints:
    """Read openmap_zone_hints.toml. Each value is a census zone name (or a list, tried in order),
    resolved to its uiMapID through the census names: no uiMapID is typed by hand. ValueError for an
    unknown table, a value that is not a zone name, or a name that is not exactly one census zone."""
    raw = read_toml(path)
    by_name: dict[str, list[int]] = {}
    for m, z in census["maps"].items():
        if z.get("mapType") == 3:
            by_name.setdefault(z.get("name"), []).append(m)
    tables = {}
    for table, rows in raw.items():
        if table not in HINT_TABLES or not isinstance(rows, dict):
            raise ValueError(f"{path}: unknown table [{table}] (expected {', '.join(HINT_TABLES)})")
        tables[table] = {}
        for name, value in rows.items():
            values = [value] if isinstance(value, str) else value
            if not isinstance(values, list) or not values or not all(isinstance(v, str) for v in values):
                raise ValueError(f"{path}: [{table}] {name!r} must be a census zone name or a list of them")
            ids = []
            for v in values:
                found = by_name.get(v, [])
                if len(found) != 1:
                    raise ValueError(f"{path}: [{table}] {name!r}: {v!r} is not exactly one census zone")
                ids.append(found[0])
            tables[table][name] = ids
    return ZoneHints(tables)


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _is_id(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _rect_ok(rect) -> bool:
    return isinstance(rect, (list, tuple)) and len(rect) == 4 and all(_num(v) for v in rect) \
        and rect[1] > rect[0] and rect[3] > rect[2]


def _zone_xy(rect, mx: float, my: float) -> tuple[float, float]:
    x1, x2, y1, y2 = rect
    return round((mx - x1) / (x2 - x1) * 100, 1), round((my - y1) / (y2 - y1) * 100, 1)


def locate(zones: dict, continent: int, mx: float, my: float, hints: ZoneHints | None = None,
           table: str | None = None, names=()) -> tuple[tuple | None, dict | None]:
    """The zone of a continent-normalized point: ((uiMapID, x, y, by), None) or (None, problem).

    zones: {uiMapID: {name, continent, rect, live[, kind]}} (curated.load_zones output). Candidates
    are the live zones on `continent` whose census rect contains the point (battlegrounds have none).
    by: "rect" when exactly one zone rect contains it; when two or more do, "hint" when the hints
    (`table`, the entries of `names`) name one of them (the first hinted zone whose rect contains
    the point; a hint beats a city rect), else "city" when one city rect contains it (it wins over
    the zones around it). A hint that names no containing zone (a route hint names every end's
    zone) leaves the point to the city rule. Problems: "no-zone", "several-cities",
    "ambiguous-zone" (no hint), "hint-outside", "conflicting-hints"; each lists every candidate
    with its zone coordinates. x, y are 0-100 on the chosen zone's map. A hint counts as used
    only when it chose a point's zone.
    """
    cands = [m for m in sorted(zones) if zones[m].get("live") and zones[m].get("continent") == continent
             and zones[m].get("kind") != "battleground" and _rect_ok(zones[m].get("rect"))
             and zones[m]["rect"][0] <= mx <= zones[m]["rect"][1] and zones[m]["rect"][2] <= my <= zones[m]["rect"][3]]
    listing = [{"map": m, "name": zones[m]["name"], **dict(zip("xy", _zone_xy(zones[m]["rect"], mx, my)))}
               for m in cands]

    def at(m, by):
        return (m, *_zone_xy(zones[m]["rect"], mx, my), by), None

    if not cands:
        return None, {"type": "no-zone", "candidates": []}
    if len(cands) == 1:
        return at(cands[0], "rect")
    hinted, matched = (hints.lookup(table, names) if hints is not None else ([], []))
    if hinted is None:
        return None, {"type": "conflicting-hints", "hint_names": matched, "candidates": listing}
    pick = next((h for h in hinted if h in cands), None)
    if pick is not None:
        hints.decided(table, matched)
        return at(pick, "hint")
    cities = [m for m in cands if zones[m].get("kind") == "city"]
    if len(cities) == 1:
        return at(cities[0], "city")
    if cities:
        return None, {"type": "several-cities", "candidates": listing}
    if hinted:
        return None, {"type": "hint-outside", "hint_names": matched,
                      "hint": [zones[h]["name"] if h in zones else h for h in hinted], "candidates": listing}
    return None, {"type": "ambiguous-zone", "candidates": listing}


# ---------------------------------------------------------------- links

def transport_links(places: dict, zones: dict, hints: ZoneHints | None = None) -> tuple[list[dict], list[dict]]:
    """One link per OpenMap transport row, from the departure zone to the arrival zone: (links, problems).

    Link: {from, to, kind, x, y (the departure, on its zone's map), label "<OpenMap kind> to <arrival
    zone>", faction, source "openmap"}. Kinds: boat, zeppelin; an airship becomes a zeppelin.
    Faction: OpenMap's field, else Horde for a zeppelin (the classic rule), else none. Hints are
    looked up by route name. Problems: "unknown-kind", "unknown-continent" (an end on a continent the
    census does not map, such as Zephras Isle's 2991; the row is not placed), a placement problem of
    either end (see locate), "self-link" (both ends in one zone). Then every link whose target has
    no link of the same kind back is reported as "missing-reverse"; no reverse is invented.
    """
    links, problems = [], []
    for t in places.get("transports") or []:
        where = {"route": t.get("route"), "openmap_kind": t.get("kind")}
        kind = TRANSPORT_KINDS.get(t.get("kind"))
        if kind is None:
            problems.append({"type": "unknown-kind", **where})
            continue
        ends = {"from": (t["continent"], t["x"], t["y"]), "to": (t["to_continent"], t["to_x"], t["to_y"])}
        unknown = [(end, c, x, y) for end, (c, x, y) in ends.items()
                   if c not in OPENMAP_CONTINENTS or not (_num(x) and _num(y))]
        if unknown:
            for end, c, x, y in unknown:
                problems.append({"type": "unknown-continent", **where, "end": end, "continent": c, "world": [x, y]})
            continue
        placed = {}
        for end, (c, x, y) in ends.items():
            continent = OPENMAP_CONTINENTS[c]
            place, problem = locate(zones, continent, *world_to_continent(continent, x, y), hints, "transports",
                                    [t["route"]])
            if problem is not None:
                problems.append({**problem, **where, "end": end, "continent": c, "world": [x, y]})
            else:
                placed[end] = place
        if len(placed) != 2:
            continue
        (src, sx, sy, _), (dst, _, _, _) = placed["from"], placed["to"]
        if src == dst:
            problems.append({"type": "self-link", **where, "map": src, "name": zones[src]["name"]})
            continue
        links.append({"from": src, "to": dst, "kind": kind, "x": sx, "y": sy,
                      "label": f"{t['kind']} to {zones[dst]['name']}",
                      "faction": t.get("faction") or TRANSPORT_FACTIONS.get(t["kind"]), "source": "openmap"})
    have = {(l["from"], l["to"], l["kind"]) for l in links}
    for l in links:
        if (l["to"], l["from"], l["kind"]) not in have:
            problems.append({"type": "missing-reverse", "from": l["from"], "to": l["to"], "kind": l["kind"],
                             "label": l["label"], "x": l["x"], "y": l["y"]})
    return links, problems


# ---------------------------------------------------------------- dungeons

def _initials(name: str) -> str:
    return "".join(w[0] for w in re.findall(r"[A-Za-z0-9][A-Za-z0-9']*", name)).upper() or "D"


def _levels_ok(lo, hi) -> bool:
    return _is_id(lo) and _is_id(hi) and 1 <= lo <= hi


def _assign_keys(entries: list[dict], seed_keys: dict[str, str]) -> dict[str, dict]:
    """Keys: a seed key for the same name, else the name's initials, deduplicated with 2, 3, ..."""
    by_name = {name_key(n): k for k, n in seed_keys.items()}
    taken, out, rest = set(seed_keys), {}, []
    for e in entries:
        key = by_name.get(name_key(e["name"]))
        if key is not None and key not in out:
            out[key] = e
        else:
            rest.append(e)
    for e in sorted(rest, key=lambda e: e["name"]):
        base = _initials(e["name"])
        key, n = base, 2
        while key in taken or key in out:
            key, n = f"{base}{n}", n + 1
        out[key] = e
    return out


def reference_dungeons(places: dict, zones: dict, hints: ZoneHints | None = None,
                       seed_keys: dict[str, str] | None = None) -> tuple[dict[str, dict], list[dict]]:
    """One entry per 5-player OpenMap instance: ({key: dungeon}, problems).

    Dungeon: {name, entrance [mapID, x, y], min_level, max_level, group_size 5, faction, live true,
    quests [], source "openmap"}. A world-yard entrance gets its zone from locate (hints looked up
    by member name, then by a wing's instance name, "Dire Maul" for "Dire Maul - East"); a `map =`
    spot is used as given (x, y times 100) when that map is a zone. Raids are skipped. Names and
    levels are OpenMap's (the Group Finder's). Faction: Alliance or Horde when the entrance is in
    one of that faction's capitals, else Both. Keys: SEED_KEYS and seed_keys ({key: name}, from
    dungeons.toml) keep a key for the same name; others are the name's initials. Problems:
    placement problems (see locate) with the instance's "names", "unknown-continent",
    "unknown-map", "bad-spot", "no-levels", "no-entrance" (OpenMap has no entrance).
    """
    problems, entries = [], []
    for g in places.get("instances") or []:
        members = [m for m in g["members"] if not m["raid"]]
        if not members:
            continue
        names = [m["name"] for m in members]
        if g.get("map") is not None:
            if not _is_id(g["map"]) or not all(_num(v) and 0 <= v <= 1 for v in (g.get("x"), g.get("y"))):
                problems.append({"type": "bad-spot", "names": names, "map": g.get("map"), "x": g.get("x"),
                                 "y": g.get("y")})
                continue
            if g["map"] not in zones:
                problems.append({"type": "unknown-map", "names": names, "map": g["map"]})
                continue
            entrance = [g["map"], round(g["x"] * 100, 4), round(g["y"] * 100, 4)]
        else:
            c, x, y = g.get("continent"), g.get("x"), g.get("y")
            if c not in OPENMAP_CONTINENTS or not (_num(x) and _num(y)):
                problems.append({"type": "unknown-continent", "names": names, "continent": c, "world": [x, y]})
                continue
            continent = OPENMAP_CONTINENTS[c]
            wings = [m["name"].partition(" - ")[0] for m in g["members"] if " - " in m["name"]]
            lookup = list(dict.fromkeys([m["name"] for m in g["members"]] + wings))
            place, problem = locate(zones, continent, *world_to_continent(continent, x, y), hints, "instances",
                                    lookup)
            if problem is not None:
                problems.append({**problem, "names": names, "continent": c, "world": [x, y]})
                continue
            entrance = list(place[:3])
        for m in members:
            if not _levels_ok(m["min_level"], m["max_level"]):
                problems.append({"type": "no-levels", "name": m["name"], "id": m["id"]})
                continue
            entries.append({"name": m["name"], "entrance": list(entrance), "min_level": m["min_level"],
                            "max_level": m["max_level"], "group_size": 5,
                            "faction": CITY_FACTIONS.get(entrance[0], "Both"), "live": True, "quests": [],
                            "source": "openmap"})
    for m in places.get("unplaced") or []:
        if not m["raid"]:
            problems.append({"type": "no-entrance", "name": m["name"], "id": m["id"]})
    return _assign_keys(entries, {**SEED_KEYS, **(seed_keys or {})}), problems


# ---------------------------------------------------------------- TOML out

def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        out = []
        for ch in v:
            if ch in '"\\':
                out.append("\\" + ch)
            elif ord(ch) < 0x20 or ord(ch) == 0x7F:
                out.append(f"\\u{ord(ch):04X}")
            else:
                out.append(ch)
        return '"' + "".join(out) + '"'
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    raise TypeError(f"cannot write {v!r} as TOML")


def links_toml(links: list[dict]) -> str:
    parts = [HEADER]
    for l in links:
        parts.append("\n[[links]]\n")
        for field in ("from", "to", "kind", "x", "y", "label", "faction", "source"):
            if l.get(field) is not None:
                parts.append(f"{field} = {_toml_value(l[field])}\n")
    return "".join(parts)


def toml_key(key: str) -> str:
    """A TOML table key: bare when it can be, else quoted."""
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else _toml_value(key)


def dungeons_toml(dungeons: dict[str, dict]) -> str:
    parts = [HEADER]
    for key in sorted(dungeons):
        parts.append(f"\n[dungeons.{toml_key(key)}]\n")
        for field in ("name", "entrance", "min_level", "max_level", "group_size", "faction", "live", "quests",
                      "source"):
            parts.append(f"{field} = {_toml_value(dungeons[key][field])}\n")
    return "".join(parts)


def write_text_atomic(path: Path, text: str) -> None:
    """Writes text to path through a temp file and os.replace, making the parent dir."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


# ---------------------------------------------------------------- CLI

def _summary(problems: list[dict]) -> str:
    counts = Counter(p["type"] for p in problems)
    return ", ".join(f"{t} {n}" for t, n in sorted(counts.items())) or "none"


def run(args, log=print) -> int:
    """CLI entry (python -m pipeline poi). 0 on success, 2 on a missing or unusable input or a failed bounds gate."""
    openmap, census_path = Path(args.openmap), Path(args.census)
    curated, problems_path = Path(args.curated), Path(args.problems)
    missing = [str(p) for p in (openmap, census_path, curated / "zones.toml") if not p.is_file()]
    if missing:
        print(f"poi: input not found: {', '.join(missing)} (see data/REFERENCE_SOURCES.md for where to get it)",
              file=sys.stderr)
        return 2
    try:
        census = read_census_json(census_path)
        bounds = check_bounds(census)
        zones = load_zones(curated / "zones.toml", census)
        hints_path = curated / HINTS_FILE
        hints = load_zone_hints(hints_path, census) if hints_path.is_file() else ZoneHints()
        places = load_openmap_places(openmap)
        seeds = {}
        if (curated / "dungeons.toml").is_file():
            seeds = {k: d["name"] for k, d in load_dungeons(curated / "dungeons.toml").items()}
    except ValueError as e:
        print(f"poi: {e}", file=sys.stderr)
        return 2

    links, link_problems = transport_links(places, zones, hints)
    dungeons, dungeon_problems = reference_dungeons(places, zones, hints, seeds)
    hint_problems = hints.unused()
    hints_used, hinted_points = len(hints.used), hints.points

    links_path = curated / "links.generated.toml"
    dungeons_path = curated / "dungeons.generated.toml"
    write_text_atomic(links_path, links_toml(links))
    write_text_atomic(dungeons_path, dungeons_toml(dungeons))
    report = {"openmap": {"path": str(openmap), "commit": OPENMAP_COMMIT}, "census": str(census_path),
              "bounds": {str(k): v for k, v in bounds.items()},
              "counts": {"links": dict(Counter(l["kind"] for l in links)), "dungeons": len(dungeons),
                         "hints_used": hints_used, "points_by_hint": hinted_points},
              "links": link_problems, "dungeons": dungeon_problems, "hints": hint_problems}
    write_text_atomic(problems_path, json.dumps(report, indent=1, ensure_ascii=False) + "\n")

    kinds = Counter(l["kind"] for l in links)
    gate = ", ".join(f"{k}: {v['difference'][0]:+.2f}, {v['difference'][1]:+.2f} yd" for k, v in bounds.items())
    log(f"poi: bounds gate passed ({gate})")
    log(f"poi: {len(links)} links ({', '.join(f'{k} {n}' for k, n in sorted(kinds.items()))}) -> {links_path}")
    log(f"poi: {len(dungeons)} dungeons -> {dungeons_path}")
    log(f"poi: {hints_used} zone hints used for {hinted_points} points, {len(hint_problems)} unused ({HINTS_FILE})")
    log(f"poi: {len(link_problems)} link problems ({_summary(link_problems)}), {len(dungeon_problems)} dungeon "
        f"problems ({_summary(dungeon_problems)}) -> {problems_path}")
    return 0
