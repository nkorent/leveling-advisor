"""Reference POI import: OpenMap (MIT) + the in-game census -> generated travel links and dungeons.

OpenMap ``OpenMap/Data/Forever/Places.lua`` lists boat, zeppelin and airship routes and dungeon
entrances in world yards per continent (0 Eastern Kingdoms, 1 Kalimdor), some entrances as a spot
on a zone map, the Group Finder's instance names and levels and a raid flag. It is a Lua chunk,
run in a fresh lupa runtime whose chunk environment is empty: no ``os``, ``io``, ``require`` or ``load``.

World yards become continent-normalized coordinates through the classic WorldMapArea continent
bounds (CONTINENT_BOUNDS), accepted only when they reproduce the census continent yards
(check_bounds). A point then gets its zone from the census zone rects (locate):

* the one live zone rect that contains it;
* where two or more live zone rects contain it (classic zone maps overlap), the zone that the
  hand-maintained data/curated/openmap_zone_hints.toml names, by OpenMap route or instance name
  and census zone name, if that zone's rect contains the point; else a city rect
  (zones.toml ``kind = "city"``), which wins over the zones around it;
* anything else is a problem. Nothing is guessed or snapped to a zone.

``python -m pipeline poi`` writes data/curated/links.generated.toml and dungeons.generated.toml
(merged by pipeline.curated under the hand-maintained files) and data/build/poi-problems.json.
"""
