"""Lua emitter: writes the addon's Data/*.lua files in the layout of Contract A.

Contract A is in docs/superpowers/plans/2026-11-24-leveling-advisor-00-overview.md; the decoder
is LevelingAdvisor/Core/DB.lua. Every file starts with HEADER, then ``local _, ns = ...`` and
``ns.Data = ns.Data or {}``. Records are positional where Contract A says so (quests, NPCs,
points, places) and named elsewhere (zones, dungeons, meta, rewards, items, prereq).

Inputs use the snake-case names of the merge (``pipeline.merge``) and of Task 7's curated loaders;
enums arrive as strings and are encoded here. An unknown enum value raises ValueError rather
than being written as nil. Coordinates (0-100 map units) are rounded to 1 decimal. Empty optional
parts (no prerequisites, no items, ...) are written as nil, which the decoder reads as empty.

Quests and NPCs are written in blocks, each its own function: LuaJIT refuses a function with more
than 65536 constants, and the full quest set would exceed that in a single table constructor.
"""
from __future__ import annotations

import math
import os
import re
from pathlib import Path

HEADER = "-- Generated by pipeline/emit.py. Do not edit."
PREAMBLE = (HEADER, "local _, ns = ...", "ns.Data = ns.Data or {}")

FACTION = {"Alliance": 1, "Horde": 2, "Both": 3}
ZONE_FACTION = {"Alliance": 1, "Horde": 2, "Both": 3, "Contested": 3}
LINK_FACTION = {"Alliance": 1, "Horde": 2}
KIND = {"npc": 1, "object": 2, "item": 3}
OBJECTIVE_KIND = {"npc": 1, "object": 2, "item": 3, "other": 4}     # Contract A field 26
SOURCE_KIND = {"npc": 1, "object": 2}                               # field 26 fromKind
SOURCE = {"game": 1, "estimate": 2, "recorder": 3}
# Contract A field 18 has no QuestieDB code: QuestieDB XP (Classic tables plus trace-observed game
# values) is game data, as Questie-filled levels already are; the merge provenance keeps "questiedb".
XP_SOURCE = {**SOURCE, "questiedb": SOURCE["game"]}
LINK_KINDS = frozenset({"walk", "boat", "zeppelin", "tram", "portal", "flight"})
# Contract A field 9: bit per merged boolean flag. class_quest (bit 2) is already narrowed by the
# merge to masks allowing 1 or 2 of the 9 classes; the class mask itself is emitted in full.
FLAG_BITS = (("elite", 1), ("class_quest", 2), ("new_in_forever", 4), ("unverified", 8),
             ("repeatable", 16), ("dungeon_quest", 32))
BLOCK_SIZE = 200   # records per function (well under LuaJIT's 65536 constants)

_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Lua 5.1 keywords, plus goto (5.2+): never written as a bare key.
_RESERVED = frozenset("and break do else elseif end false for function if in local nil not or repeat "
                      "return then true until while goto".split())
_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


# ---------------------------------------------------------------- literals

def _lua_string(s: str) -> str:
    out = []
    for ch in s:
        if ch in _ESCAPES:
            out.append(_ESCAPES[ch])
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")       # 3 digits: a following digit cannot join the escape
        else:
            out.append(ch)                        # UTF-8 text is written as is
    return '"' + "".join(out) + '"'


def _key(k) -> str:
    if isinstance(k, str) and _IDENT_RE.match(k) and k not in _RESERVED:
        return k
    if isinstance(k, bool) or not isinstance(k, (str, int, float)):
        raise TypeError(f"unsupported Lua table key: {k!r}")
    return f"[{lua_literal(k)}]"


def lua_literal(value) -> str:
    """Python value -> Lua 5.1 source text.

    None -> nil; bool; int; float (shortest round-trip form; callers round coordinates to 1
    decimal); str (escaped, UTF-8 kept); list/tuple -> {a, b} (trailing nils dropped); dict ->
    {key = v} for identifier keys, {[k] = v} otherwise (None values are left out).
    """
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"no Lua literal for {value!r}")
        return repr(value)
    if isinstance(value, str):
        return _lua_string(value)
    if isinstance(value, (list, tuple)):
        items = list(value)
        while items and items[-1] is None:
            items.pop()
        return "{" + ", ".join(lua_literal(v) for v in items) + "}"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_key(k)} = {lua_literal(v)}" for k, v in value.items() if v is not None) + "}"
    raise TypeError(f"no Lua literal for {type(value).__name__}: {value!r}")


# ---------------------------------------------------------------- encoders

def _enum(table: dict, value, what: str):
    if value is None:
        return None
    if value not in table:
        raise ValueError(f"unknown {what}: {value!r}")
    return table[value]


def _coord(v):
    return None if v is None else round(float(v), 1)


def _place(p: dict | None) -> list | None:
    """{kind, id, map_id, x, y} -> {kind, id, mapID, x, y}."""
    if p is None:
        return None
    return [_enum(KIND, p.get("kind"), "place kind"), p.get("id"), p.get("map_id"), _coord(p.get("x")),
            _coord(p.get("y"))]


def _point(p: dict) -> list:
    return [p.get("map_id"), _coord(p.get("x")), _coord(p.get("y"))]


def _objective_point(p: dict) -> list:
    """{map_id, x, y, objective} -> {mapID, x, y, objectiveIndex} (field 13; index nil when unmatched)."""
    return [*_point(p), p.get("objective")]


def _objective(ob: dict) -> list:
    """Merged objective -> {kind, id, name, count, from, fromKind, fromMore} (field 26)."""
    return [_enum(OBJECTIVE_KIND, ob.get("kind"), "objective kind"), ob.get("id"), ob.get("name"), ob.get("count"),
            list(ob.get("from") or []) or None, _enum(SOURCE_KIND, ob.get("from_kind"), "objective source kind"),
            True if ob.get("from_more") else None]


def _pairs(entries, a: str, b: str) -> list | None:
    out = [[e[a], e[b]] for e in entries or []]
    return out or None


def _named(**parts) -> dict | None:
    """Table of the non-empty parts, or None when every part is empty."""
    kept = {k: v for k, v in parts.items() if v not in (None, [], {})}
    return kept or None


def _flags(q: dict) -> int:
    return sum(bit for name, bit in FLAG_BITS if q.get(name))


def encode_quest(q: dict) -> list:
    """Merged quest -> Contract A positional record (Python list; index 0 is Lua position 1)."""
    items = q.get("items") or {}
    rewards = q.get("rewards") or {}
    prereq = q.get("prereq") or {}
    chain = q.get("chain")
    return [
        q.get("name"),                                                   # 1
        _enum(FACTION, q.get("faction"), "faction"),                     # 2
        q.get("race_mask") or None,                                      # 3
        q.get("class_mask") or None,                                     # 4
        q.get("required_level"),                                         # 5
        q.get("quest_level"),                                            # 6
        _enum(SOURCE, q.get("level_source"), "level source"),            # 7
        q.get("zone_map_id"),                                            # 8
        _flags(q),                                                       # 9
        q.get("group_size"),                                             # 10
        _place(q.get("giver")),                                          # 11
        _place(q.get("turn_in")),                                        # 12
        [_objective_point(p) for p in q.get("objective_points") or []] or None,  # 13
        q.get("objective_text"),                                         # 14
        _named(provided=list(items.get("provided") or []),               # 15
               required=_pairs(items.get("required"), "item_id", "count")),
        _named(choice=_pairs(rewards.get("choice"), "item_id", "count"),  # 16
               fixed=_pairs(rewards.get("fixed"), "item_id", "count"),
               spellID=rewards.get("spell_id"),
               money=rewards.get("money") or None,
               rep=_pairs(rewards.get("rep"), "faction", "amount")),
        q.get("xp"),                                                     # 17
        _enum(XP_SOURCE, q.get("xp_source"), "xp source"),               # 18
        _named(all=list(prereq.get("all") or []), any=list(prereq.get("any") or [])),  # 19
        list(q.get("exclusive_to") or []) or None,                       # 20
        q.get("breadcrumb_of"),                                          # 21
        [chain["chain_id"], chain["index"], chain["length"]] if chain else None,  # 22
        q.get("dungeon_key"),                                            # 23
        q.get("required_max_level"),                                     # 24 (Contract A addition)
        list(q.get("unavailable_after") or []) or None,                  # 25 (Contract A addition)
        [_objective(ob) for ob in q.get("objectives") or []] or None,    # 26 (Contract A addition)
    ]


def encode_stub(s: dict) -> list:
    """Quest stub (merge _stubs) -> Contract A questStubs positional record (fields 1-9)."""
    prereq = s.get("prereq") or {}
    giver = s.get("giver")
    start = _named(kind=_enum(KIND, giver.get("kind"), "place kind"), name=s.get("start_name"),
                   mapID=giver.get("map_id")) if giver else None
    return [
        s.get("name"),                                                   # 1
        s.get("level"),                                                  # 2
        s.get("required_level"),                                         # 3
        _enum(FACTION, s.get("faction"), "faction"),                     # 4
        s.get("race_mask") or None,                                      # 5
        s.get("class_mask") or None,                                     # 6
        _named(all=list(prereq.get("all") or []), any=list(prereq.get("any") or [])),  # 7
        start,                                                           # 8
        s.get("reason"),                                                 # 9
    ]


def encode_npc(n: dict) -> list:
    """outof.games NPC (parse_npc) -> {name, faction, level, { {mapID, x, y}, ... }}."""
    spawns = [_point(s) for s in n.get("spawns") or []]
    return [n.get("name"), _enum(FACTION, n.get("faction"), "NPC faction"), n.get("level"), spawns or None]


def _link(link: dict) -> dict:
    kind = link.get("kind")
    if kind not in LINK_KINDS:
        raise ValueError(f"unknown link kind: {kind!r}")
    return {"to": link.get("to"), "kind": kind, "x": _coord(link.get("x")), "y": _coord(link.get("y")),
            "label": link.get("label"), "faction": _enum(LINK_FACTION, link.get("faction"), "link faction")}


def _zone_faction(value):
    if isinstance(value, int) and not isinstance(value, bool) and value in (1, 2, 3):
        return value
    return _enum(ZONE_FACTION, value, "zone faction")


def encode_zone(z: dict) -> dict:
    return {
        "name": z.get("name"),
        "continent": z.get("continent"),
        "faction": _zone_faction(z.get("faction")),
        "minLevel": z.get("min_level"),
        "maxLevel": z.get("max_level"),
        "live": bool(z.get("live")),
        "complete": bool(z.get("complete")),
        "yards": list(z["yards"]) if z.get("yards") else None,
        "rect": list(z["rect"]) if z.get("rect") else None,
        "links": [_link(link) for link in z.get("links") or []],
        "kind": z.get("kind") or None,     # "city" | "battleground" | nil (a leveling zone)
    }


def encode_dungeon(d: dict) -> dict:
    entrance = d.get("entrance")
    return {
        "name": d.get("name"),
        "entrance": [entrance[0], _coord(entrance[1]), _coord(entrance[2])] if entrance else None,
        "minLevel": d.get("min_level"),
        "maxLevel": d.get("max_level"),
        "groupSize": d.get("group_size"),
        "faction": _zone_faction(d.get("faction")),
        "live": bool(d.get("live")),
        "quests": list(d.get("quests") or []),
    }


# ---------------------------------------------------------------- files

def _write(path: Path, lines: list[str]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def _table_file(path: Path, var: str, entries: list[tuple]) -> None:
    """ns.Data.<var> = { [key] = value, ... } as one constructor (small tables)."""
    lines = [*PREAMBLE, "", f"ns.Data.{var} = {{"]
    lines += [f"  {_key(k)} = {lua_literal(v)}," for k, v in entries]
    lines.append("}")
    _write(path, lines)


def _block_file(path: Path, var: str, entries: list[tuple], extra: tuple | None = None) -> None:
    """ns.Data.<var> filled in blocks of BLOCK_SIZE records, each block its own function.
    extra: (var, entries) for a second table in the same file, blocked the same way."""
    lines = [*PREAMBLE, "", "local t = {}", f"ns.Data.{var} = t",
             "-- one function per block: LuaJIT allows at most 65536 constants per function",
             "local function block(fill) fill(t) end"]
    for start in range(0, len(entries), BLOCK_SIZE):
        lines += ["", "block(function(t)"]
        lines += [f"t[{lua_literal(k)}] = {lua_literal(v)}" for k, v in entries[start:start + BLOCK_SIZE]]
        lines.append("end)")
    if extra:
        name, rows = extra
        lines += ["", f"local {name} = {{}}", f"ns.Data.{name} = {name}",
                  f"local function {name}Block(fill) fill({name}) end"]
        for start in range(0, len(rows), BLOCK_SIZE):
            lines += ["", f"{name}Block(function(t)"]
            lines += [f"t[{lua_literal(k)}] = {lua_literal(v)}" for k, v in rows[start:start + BLOCK_SIZE]]
            lines.append("end)")
    _write(path, lines)


def emit_quests(quests: dict[int, dict], path: Path, stubs: dict[int, dict] | None = None) -> None:
    """Data/Quests.lua: ns.Data.quests = { [questID] = { positional fields 1-26 } } and
    ns.Data.questStubs = { [questID] = { positional fields 1-9 } } (always present, maybe empty)."""
    _block_file(path, "quests", [(int(qid), encode_quest(quests[qid])) for qid in sorted(quests)],
                extra=("questStubs", [(int(qid), encode_stub(stubs[qid])) for qid in sorted(stubs or {})]))


def emit_npcs(npcs: dict[int, dict], path: Path) -> None:
    """Data/NPCs.lua from outof.games NPC dicts: { [npcID] = { name, faction, level, spawns } }."""
    _block_file(path, "npcs", [(int(nid), encode_npc(npcs[nid])) for nid in sorted(npcs)])


def emit_zones(zones: dict[int, dict], continents: dict[int, dict], path: Path) -> None:
    """Data/Zones.lua: ns.Data.zones and ns.Data.continents.

    zones: {uiMapID: {name, continent, faction ("Alliance" | "Horde" | "Contested" | "Both" | 1-3),
    min_level, max_level, live, complete, yards, rect, kind ("city" | "battleground" | absent),
    links: [{to, kind, x, y, label, faction}]}}.
    continents: census maps ({uiMapID: {name, mapType, yards, ...}}); only maps with mapType == 2
    (Continent) are written, with their name and yards.
    """
    lines = [*PREAMBLE, "", "ns.Data.zones = {"]
    lines += [f"  [{int(mid)}] = {lua_literal(encode_zone(zones[mid]))}," for mid in sorted(zones)]
    lines += ["}", "", "ns.Data.continents = {"]
    for mid in sorted(continents or {}):
        m = continents[mid]
        if m.get("mapType") == 2:
            value = {"name": m.get("name"), "yards": list(m["yards"]) if m.get("yards") else None}
            lines.append(f"  [{int(mid)}] = {lua_literal(value)},")
    lines.append("}")
    _write(path, lines)


def emit_dungeons(dungeons: dict[str, dict], path: Path) -> None:
    """Data/Dungeons.lua: ns.Data.dungeons = { [key] = { name=, entrance={mapID, x, y}, ... } }."""
    _table_file(path, "dungeons", [(key, encode_dungeon(dungeons[key])) for key in sorted(dungeons)])


def emit_meta(meta: dict, path: Path) -> None:
    """Data/Meta.lua: ns.Data.meta = { built=, gameData=, sources={...}, counts={...}, ... }."""
    _write(path, [*PREAMBLE, "", f"ns.Data.meta = {lua_literal(meta)}"])
